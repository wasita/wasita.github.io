      >
        motivating questions
      </h2>
      <p>
        We only ever have direct access to our own thoughts, feelings, and
        experiences. Yet in the middle of interacting and talking with someone
        else, we infer, moment by moment, what they think, feel, and care about
        from what they say and do. Sometimes we come to feel genuinely
        connected as a result. What cognitive process turns those inferences
        into felt connection? And why do others lead to disconnect instead?
      </p>
