      <h2
        class="font-display mb-4"
        style="font-size: clamp(1.75rem, 4vw, 2.5rem); line-height: 1; color: var(--accent);"
      >
        the dissertation
      </h2>
      <p>
        My dissertation develops an inferential account of social connection,
        a framework for how people read another's inner world from what a
        real-time interaction actually provides. That includes a single stance
        on a topic, a partner's reaction to a shared moment as it unfolds, or
        the depth and rarity of a disclosed experience. I combine custom
        multi-user web paradigms with computational modeling (primarily
        Bayesian inference) and NLP to study these inferences during social
        interactions. Across three
        studies, I have shown connection emerges not from the quantity of
        commonalities but from the inferences people draw on top of them.
      </p>
    </section>

    <section>
      <h2
        class="font-display mb-4"
        style="font-size: clamp(1.75rem, 4vw, 2.5rem); line-height: 1; color: var(--accent);"
      >
        what's next
      </h2>
      <p>
        As a postdoc, I aim to build on my dissertation work by developing
        computational models of interacting minds. Most models of social
        cognition only consider one mind at a time, with an observer reasoning
        about a passive target. In real interaction, two minds update on each
        other in the same loop, and that interdependence changes the
        computation. I plan to build multi-agent models of coordination,
        capturing how each partner's inferences and actions shape the other's,
        and to test them with simulation experiments and behavioral data from
        custom multi-user paradigms. I will start with joint planning as a
        natural first problem space, before extending to richer social settings. Longer term, I want
        to use these models to ask why these processes break down in many
        psychiatric conditions. My goal is to formalize a mechanistic theory of
        how coordination between minds gives rise to, or fails to give rise to,
        the feeling of being truly understood by another.
